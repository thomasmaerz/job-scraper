    'Conservative lower bound for accepted same-ID relist events: the listing was relisted at least once when greater than zero.';

CREATE TABLE IF NOT EXISTS public.ingestion_runs (
    id uuid PRIMARY KEY,
    provider text NOT NULL,
    search_query text,
    archetype text,
    filter_profile text,
    query_scope text NOT NULL DEFAULT '',
    started_at timestamp with time zone NOT NULL DEFAULT now(),
    finished_at timestamp with time zone,
    status text NOT NULL DEFAULT 'running',
    pages_attempted integer NOT NULL DEFAULT 0 CHECK (pages_attempted >= 0),
    pages_completed integer NOT NULL DEFAULT 0 CHECK (pages_completed >= 0),
    cards_seen integer NOT NULL DEFAULT 0 CHECK (cards_seen >= 0),
    detail_budget_used integer NOT NULL DEFAULT 0 CHECK (detail_budget_used >= 0),
    coverage_complete boolean NOT NULL DEFAULT false,
    coverage_reason text,
    created_at timestamp with time zone NOT NULL DEFAULT now()
);
ALTER TABLE public.ingestion_runs ADD COLUMN IF NOT EXISTS query_scope text NOT NULL DEFAULT '';
UPDATE public.ingestion_runs
SET pages_completed = LEAST(pages_completed, pages_attempted),
    status = CASE WHEN status IN ('running', 'complete', 'incomplete', 'failed') THEN status ELSE 'failed' END;
ALTER TABLE public.ingestion_runs DROP CONSTRAINT IF EXISTS ingestion_runs_status_check;
ALTER TABLE public.ingestion_runs ADD CONSTRAINT ingestion_runs_status_check
    CHECK (status IN ('running', 'complete', 'incomplete', 'failed'));
ALTER TABLE public.ingestion_runs DROP CONSTRAINT IF EXISTS ingestion_runs_page_coverage_check;
ALTER TABLE public.ingestion_runs ADD CONSTRAINT ingestion_runs_page_coverage_check
    CHECK (pages_completed <= pages_attempted);

