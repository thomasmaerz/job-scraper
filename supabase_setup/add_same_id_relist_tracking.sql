CREATE TABLE IF NOT EXISTS public.listing_relist_events (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    provider text NOT NULL,
    source_job_id text NOT NULL,
    canonical_job_id text REFERENCES public.jobs(job_id) ON DELETE SET NULL,
    relisted_on date NOT NULL,
