CREATE OR REPLACE FUNCTION public.finalize_freehire_publication(p_source_scrape_watermark timestamptz)
RETURNS TABLE (generation bigint, published_at timestamptz, source_scrape_watermark timestamptz, row_count bigint, schema_version text)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog
AS $publication$
DECLARE
    current_state public.freehire_publication_state%ROWTYPE;
    next_generation bigint;
    copied_count bigint;
BEGIN
    PERFORM pg_catalog.set_config('lock_timeout', '10s', true);
    PERFORM pg_catalog.set_config('statement_timeout', '5min', true);
    PERFORM pg_catalog.set_config('idle_in_transaction_session_timeout', '6min', true);
    IF p_source_scrape_watermark IS NULL THEN
        RAISE EXCEPTION 'p_source_scrape_watermark must not be null' USING ERRCODE = '22004';
    END IF;
    SELECT * INTO STRICT current_state
    FROM public.freehire_publication_state AS state WHERE state.id = 1 FOR UPDATE;
    IF current_state.source_scrape_watermark = p_source_scrape_watermark THEN
        RETURN QUERY SELECT current_state.generation, current_state.published_at,
            current_state.source_scrape_watermark, current_state.row_count, current_state.schema_version;
        RETURN;
    END IF;
    IF current_state.source_scrape_watermark IS NOT NULL
       AND p_source_scrape_watermark < current_state.source_scrape_watermark THEN
        RAISE EXCEPTION 'source scrape watermark cannot move backwards (% < %)',
            p_source_scrape_watermark, current_state.source_scrape_watermark USING ERRCODE = '22000';
    END IF;
    next_generation := current_state.generation + 1;
    INSERT INTO public.freehire_publication_snapshots (generation, canonical_job_id, import_hash, payload)
    SELECT next_generation, source.job_id, source.freehire_compat_import_hash, pg_catalog.to_jsonb(source)
    FROM public.freehire_jobs AS source ORDER BY source.job_id;
    GET DIAGNOSTICS copied_count = ROW_COUNT;
    UPDATE public.freehire_publication_state AS state
    SET generation = next_generation, published_at = pg_catalog.clock_timestamp(),
        source_scrape_watermark = p_source_scrape_watermark, row_count = copied_count,
        schema_version = 'freehire-publication-v1'
    WHERE state.id = 1
    RETURNING state.generation, state.published_at, state.source_scrape_watermark,
              state.row_count, state.schema_version
    INTO current_state.generation, current_state.published_at,
         current_state.source_scrape_watermark, current_state.row_count, current_state.schema_version;
    DELETE FROM public.freehire_publication_snapshots AS snapshot
    WHERE snapshot.generation < next_generation - 2;
    RETURN QUERY SELECT current_state.generation, current_state.published_at,
        current_state.source_scrape_watermark, current_state.row_count, current_state.schema_version;
END;
$publication$;

