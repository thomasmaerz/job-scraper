CREATE OR REPLACE FUNCTION public.apply_linkedin_relist_projection(
    p_canonical_job_id text,
    p_source_job_id text,
    p_ingestion_run_id uuid,
    p_relisted_on date,
    p_observed_at timestamptz,
    p_projection jsonb,
    p_expected_listing_instances jsonb,
    p_expected_last_seen_at timestamptz,
    p_evidence jsonb,
    p_description text,
    p_content_hash text,
    p_description_fingerprint text
) RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    affected integer;
BEGIN
    IF p_relisted_on IS NULL OR p_content_hash IS NULL OR p_description IS NULL THEN
        RETURN false;
    END IF;
    UPDATE public.jobs
    SET listing_instances = p_projection->'listing_instances',
        seen_count = (p_projection->>'seen_count')::integer,
        posting_wave_count = (p_projection->>'posting_wave_count')::integer,
        repost_count = (p_projection->>'repost_count')::integer,
        same_id_relist_count = (p_projection->>'same_id_relist_count')::integer,
        latest_job_id = p_projection->>'latest_job_id',
        last_seen_at = (p_projection->>'last_seen_at')::timestamptz,
        last_seen_posted_at = NULLIF(p_projection->>'last_seen_posted_at', '')::timestamptz,
        description = COALESCE(p_projection->>'description', description),
        description_fingerprint = COALESCE(p_projection->>'description_fingerprint', description_fingerprint),
        is_active = COALESCE((p_projection->>'is_active')::boolean, is_active),
        job_state = COALESCE(p_projection->>'job_state', job_state)
    WHERE job_id = p_canonical_job_id
      AND listing_instances = p_expected_listing_instances
      AND last_seen_at IS NOT DISTINCT FROM p_expected_last_seen_at;
    GET DIAGNOSTICS affected = ROW_COUNT;
    IF affected <> 1 THEN
        RETURN false;
    END IF;

    INSERT INTO public.listing_relist_events (
        provider, source_job_id, canonical_job_id, relisted_on, observed_at,
        ingestion_run_id, evidence
    ) VALUES (
        'linkedin', p_source_job_id, p_canonical_job_id, p_relisted_on,
        p_observed_at, p_ingestion_run_id, COALESCE(p_evidence, '{}'::jsonb)
    ) ON CONFLICT (provider, source_job_id, relisted_on) DO NOTHING;

    INSERT INTO public.listing_content_versions (
        provider, source_job_id, content_hash, canonical_job_id, description,
        description_fingerprint, first_observed_at, last_observed_at,
        observation_count, last_ingestion_run_id
    ) VALUES (
        'linkedin', p_source_job_id, p_content_hash, p_canonical_job_id,
        p_description, p_description_fingerprint, p_observed_at, p_observed_at,
        1, p_ingestion_run_id
    ) ON CONFLICT (provider, source_job_id, content_hash) DO UPDATE SET
        canonical_job_id = EXCLUDED.canonical_job_id,
        description = EXCLUDED.description,
        description_fingerprint = EXCLUDED.description_fingerprint,
        last_observed_at = GREATEST(listing_content_versions.last_observed_at, EXCLUDED.last_observed_at),
        last_ingestion_run_id = EXCLUDED.last_ingestion_run_id,
        observation_count = CASE
            WHEN listing_content_versions.last_ingestion_run_id IS DISTINCT FROM EXCLUDED.last_ingestion_run_id
            THEN listing_content_versions.observation_count + 1
            ELSE listing_content_versions.observation_count
        END;

    INSERT INTO public.listing_states (
        provider, source_job_id, canonical_job_id, first_seen_at, last_seen_at,
        latest_trusted_posted_date, current_content_hash, same_id_relist_count
    ) VALUES (
        'linkedin', p_source_job_id, p_canonical_job_id, p_observed_at,
        p_observed_at, p_relisted_on, p_content_hash,
        (p_projection->>'same_id_relist_count')::integer
    ) ON CONFLICT (provider, source_job_id) DO UPDATE SET
        canonical_job_id = EXCLUDED.canonical_job_id,
        last_seen_at = EXCLUDED.last_seen_at,
        latest_trusted_posted_date = EXCLUDED.latest_trusted_posted_date,
        current_content_hash = EXCLUDED.current_content_hash,
        same_id_relist_count = GREATEST(listing_states.same_id_relist_count, EXCLUDED.same_id_relist_count),
        updated_at = now();

    UPDATE public.listing_states
    SET pending_relist_on = NULL,
        same_id_relist_count = GREATEST(
            same_id_relist_count,
            (p_projection->>'same_id_relist_count')::integer
        ),
        current_content_hash = p_content_hash,
        updated_at = now()
    WHERE provider = 'linkedin'
      AND source_job_id = p_source_job_id
      AND pending_relist_on = p_relisted_on;

    RETURN true;
END;
$$;
REVOKE ALL ON FUNCTION public.apply_linkedin_relist_projection(text, text, uuid, date, timestamptz, jsonb, jsonb, timestamptz, jsonb, text, text, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.apply_linkedin_relist_projection(text, text, uuid, date, timestamptz, jsonb, jsonb, timestamptz, jsonb, text, text, text) TO service_role;

-- Seed only directly evidenced historical facts. Re-running this migration is safe.
INSERT INTO public.listing_content_versions (
    provider, source_job_id, content_hash, canonical_job_id, description,
    description_fingerprint, first_observed_at, last_observed_at
)
SELECT
    'linkedin', COALESCE(NULLIF(j.latest_job_id, ''), j.job_id),
    encode(extensions.digest(replace(replace(trim(j.description), E'\r\n', E'\n'), E'\r', E'\n'), 'sha256'), 'hex'),
    j.job_id, j.description, j.description_fingerprint,
    COALESCE(j.first_seen_at, j.scraped_at, now()),
    COALESCE(j.last_seen_at, j.scraped_at, now())
FROM public.jobs j
WHERE j.provider = 'linkedin' AND j.description IS NOT NULL
ON CONFLICT (provider, source_job_id, content_hash) DO NOTHING;

WITH instances AS (
    SELECT
        j.job_id AS canonical_job_id,
        instance->>'job_id' AS source_job_id,
        NULLIF(instance->>'posted_at', '')::date AS relisted_on,
        COALESCE(NULLIF(instance->>'last_seen_at', '')::timestamptz, j.last_seen_at, j.scraped_at, now()) AS observed_at,
        min(NULLIF(instance->>'posted_at', '')::date) OVER (
            PARTITION BY j.job_id, instance->>'job_id'
        ) AS first_posted_on
    FROM public.jobs j
    CROSS JOIN LATERAL jsonb_array_elements(COALESCE(j.listing_instances, '[]'::jsonb)) instance
    WHERE j.provider = 'linkedin'
      AND instance->>'job_id' IS NOT NULL
      AND NULLIF(instance->>'posted_at', '') IS NOT NULL
)
INSERT INTO public.listing_relist_events (
    provider, source_job_id, canonical_job_id, relisted_on, observed_at, evidence
)
SELECT
    'linkedin', source_job_id, canonical_job_id, relisted_on, observed_at,
    jsonb_build_object('source', 'historical_listing_instances_seed', 'lower_bound', true)
FROM instances
WHERE relisted_on > first_posted_on
    ON CONFLICT (provider, source_job_id, relisted_on) DO NOTHING;

COMMIT;
