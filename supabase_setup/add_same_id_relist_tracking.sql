CREATE OR REPLACE FUNCTION public.prevent_listing_observation_mutation()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
    RAISE EXCEPTION 'listing_observations is append-only';
END;
$$;

DROP TRIGGER IF EXISTS listing_observations_append_only ON public.listing_observations;
CREATE TRIGGER listing_observations_append_only
    BEFORE UPDATE OR DELETE ON public.listing_observations
    FOR EACH ROW EXECUTE FUNCTION public.prevent_listing_observation_mutation();

