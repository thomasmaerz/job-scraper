REVOKE ALL ON TABLE public.listing_content_versions FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.listing_relist_events FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.listing_states FROM PUBLIC, anon, authenticated;
